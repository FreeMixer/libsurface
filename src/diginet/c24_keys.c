const size_t surface_c24_nkeys = sizeof surface_c24_keys / sizeof surface_c24_keys[0];

const struct surface_c24_key *surface_c24_key_find(uint16_t key)
{
	uint8_t button = (key >> 8) & 0x7f, id = key & 0xff;
	int section = id >= SURFACE_C24_ZONE_FIRST && id <= SURFACE_C24_ZONE_LAST;
	for (size_t i = 0; i < surface_c24_nkeys; i++) {
		const struct surface_c24_key *k = &surface_c24_keys[i];
		if (k->button == button && (section ? k->zone == id : k->zone == 0))
			return k;
	}
	return NULL;
}
